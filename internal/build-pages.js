function page(slug) {
  const c = CONTENT[slug];
  const url = SITE + slug + '/';
  const others = L.PAGES.filter((p) => p.slug !== slug);
  const jsonLd = [
    L.orgJsonLd(SITE),
    { '@context': 'https://schema.org', '@type': 'Service', name: c.h1, serviceType: c.service, url,
      provider: { '@id': SITE + '#org' }, areaServed: [{ '@type': 'City', name: 'Москва' }, { '@type': 'AdministrativeArea', name: 'Московская область' }] },
    L.breadcrumbsJsonLd(SITE, [{ name: c.crumb, url }]),
    L.faqJsonLd(c.faq)
  ];
  const html = L.head({ root: ROOT, siteUrl: SITE, title: c.title, description: c.description, canonical: url, jsonLd }) +
    L.header(ROOT) + `
<main id="top">
  <section class="page-hero dark" aria-labelledby="page-title">
    <div class="wrap">
      <div data-reveal>
        ${L.crumbs(ROOT, [{ name: c.crumb }])}
        <h1 id="page-title">${L.esc(c.h1)}</h1>
        <p class="hero-lead">${L.esc(c.lead)}</p>
        <ul class="page-points">
${c.points.map((p) => `          <li>${L.ICON.check}<span>${L.esc(p)}</span></li>`).join('\n')}
        </ul>
      </div>
      <div data-reveal style="--d:.1s">${L.withRoot(L.leadForm('Узнать цену машины'), ROOT)}
      </div>
    </div>
  </section>

  <section class="section" aria-labelledby="tiles-title">
    <div class="wrap">
      <div class="section-head" data-reveal>
        <div class="section-titles">
          <h2 class="display" id="tiles-title">${L.esc(c.tilesTitle)}</h2>
        </div>
      </div>
      <ul class="tiles cols cols-4">
${c.tiles.map(([h, p], i) => `        <li class="tile" data-reveal style="--d:${(i % 4) * 0.08}s"><h3>${L.esc(h)}</h3><p>${L.esc(p)}</p></li>`).join('\n')}
      </ul>
    </div>
  </section>

  <section class="section">
    <div class="wrap">
      <article class="prose" data-reveal>
${c.text.map(([h, ps]) => `        <h2>${L.esc(h)}</h2>\n${ps.map((p) => `        <p>${L.esc(p)}</p>`).join('\n')}`).join('\n')}
      </article>
    </div>
  </section>

  <section class="section" id="process" aria-labelledby="process-title">
    <div class="wrap">
      <div class="section-head" data-reveal>
        <div class="section-titles">
          <p class="eyebrow">Выкуп</p>
          <h2 class="display" id="process-title">Три шага до денег</h2>
        </div>
        <p class="lead">От звонка до расчёта — обычно один день.</p>
      </div>
      <ol class="tiles steps">
${STEPS.map(([h, p], i) => `        <li class="tile" data-reveal style="--d:${i * 0.1}s">
          <div class="step-top"><span class="step-no">0${i + 1}</span></div>
          <h3>${L.esc(h)}</h3>
          <p>${L.esc(p)}</p>
        </li>`).join('\n')}
      </ol>
      <div class="related" data-reveal>
        <a href="${ROOT}">Срочный выкуп авто</a>
${others.map((p) => `        <a href="${ROOT}${p.slug}/">Выкуп: ${L.esc(p.nav.toLowerCase())}</a>`).join('\n')}
        <a href="${ROOT}cars/">Машины в продаже</a>
      </div>
    </div>
  </section>
` + L.band() + L.faq(c.faq) + `
</main>` + L.footer(ROOT);
  return html;
}

for (const p of L.PAGES) {
  const dir = path.join(OUT, p.slug);
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, 'index.html'), page(p.slug));
  console.log('ando-site/' + p.slug + '/index.html');
}
